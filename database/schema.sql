CREATE DATABASE IF NOT EXISTS teamdev_proxy CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE teamdev_proxy;
CREATE TABLE IF NOT EXISTS urls (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, token VARCHAR(62) NOT NULL UNIQUE,
 label VARCHAR(255) NOT NULL DEFAULT '', target_url TEXT NOT NULL,
 captcha_enabled TINYINT(1) NOT NULL DEFAULT 1, expiry_hours INT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1, clicks BIGINT UNSIGNED NOT NULL DEFAULT 0,
 visits BIGINT UNSIGNED NOT NULL DEFAULT 0, blocked BIGINT UNSIGNED NOT NULL DEFAULT 0,
 bots BIGINT UNSIGNED NOT NULL DEFAULT 0, captcha_fails BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, last_visit DATETIME NULL,
 INDEX idx_urls_created (created), INDEX idx_urls_active (active)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS redirects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, token VARCHAR(32) NOT NULL UNIQUE,
 url TEXT NOT NULL, api_key VARCHAR(80) NULL, label VARCHAR(255) NULL, source VARCHAR(32) NULL,
 created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, expires DATETIME NULL,
 permanent TINYINT(1) NOT NULL DEFAULT 1, INDEX idx_redirects_created (created), INDEX idx_redirects_source (source)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sid VARCHAR(128) NOT NULL UNIQUE,
 token VARCHAR(62) NOT NULL, target TEXT NOT NULL, expires DATETIME NOT NULL,
 ip VARCHAR(45) NOT NULL, used TINYINT(1) NOT NULL DEFAULT 0,
 INDEX idx_sessions_expires (expires), INDEX idx_sessions_token (token)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS visits (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, token VARCHAR(62) NOT NULL,
 ip VARCHAR(45) NOT NULL, ua TEXT NOT NULL, device VARCHAR(32) NOT NULL DEFAULT 'Desktop',
 browser VARCHAR(32) NOT NULL DEFAULT 'Other', os VARCHAR(32) NOT NULL DEFAULT 'Other',
 referer TEXT NULL, status VARCHAR(32) NOT NULL, reason TEXT NULL,
 ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX idx_visits_token_ts (token, ts),
 INDEX idx_visits_status_ts (status, ts), INDEX idx_visits_ts (ts), INDEX idx_visits_ip (ip)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS blocked (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ip VARCHAR(45) NOT NULL UNIQUE,
 reason TEXT NULL, ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS apikeys (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, key_value VARCHAR(80) NOT NULL UNIQUE,
 label VARCHAR(255) NOT NULL DEFAULT '', active TINYINT(1) NOT NULL DEFAULT 1,
 usage_count BIGINT UNSIGNED NOT NULL DEFAULT 0, created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_used DATETIME NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS config (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, config_key VARCHAR(64) NOT NULL UNIQUE,
 shortener_url TEXT NULL, shortener_api_key TEXT NULL, enabled TINYINT(1) NOT NULL DEFAULT 0,
 updated DATETIME NULL
) ENGINE=InnoDB;