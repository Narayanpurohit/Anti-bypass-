-- One MySQL database with three logical table groups:
-- 1) identity/user data, 2) global website configuration, 3) protected link data.
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(64) NOT NULL UNIQUE,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('super_admin','user') NOT NULL DEFAULT 'user',
 status ENUM('active','blocked') NOT NULL DEFAULT 'active',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_login_at DATETIME NULL,
 INDEX idx_users_status (status)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS user_settings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 theme ENUM('light','dark') NOT NULL DEFAULT 'dark',
 timezone VARCHAR(64) NOT NULL DEFAULT 'UTC',
 dashboard_default VARCHAR(32) NOT NULL DEFAULT 'user',
 shortener_domain VARCHAR(2048) NULL DEFAULT NULL,
 shortener_api_key_encrypted TEXT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_user_settings_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS site_settings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 setting_key VARCHAR(100) NOT NULL UNIQUE,
 setting_value MEDIUMTEXT NULL,
 is_secret TINYINT(1) NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS urls (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL,
 token VARCHAR(62) NOT NULL UNIQUE, label VARCHAR(255) NOT NULL DEFAULT '', target_url TEXT NOT NULL,
 captcha_enabled TINYINT(1) NOT NULL DEFAULT 1, expiry_hours INT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1, clicks BIGINT UNSIGNED NOT NULL DEFAULT 0,
 visits BIGINT UNSIGNED NOT NULL DEFAULT 0, blocked BIGINT UNSIGNED NOT NULL DEFAULT 0,
 bots BIGINT UNSIGNED NOT NULL DEFAULT 0, captcha_fails BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, last_visit DATETIME NULL,
 INDEX idx_urls_user_created (user_id, created), INDEX idx_urls_created (created), INDEX idx_urls_active (active),
 CONSTRAINT fk_urls_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS redirects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL,
 token VARCHAR(32) NOT NULL UNIQUE, url TEXT NOT NULL, api_key VARCHAR(80) NULL,
 label VARCHAR(255) NULL, source VARCHAR(32) NULL, created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires DATETIME NULL, permanent TINYINT(1) NOT NULL DEFAULT 1,
 INDEX idx_redirects_user_created (user_id, created), INDEX idx_redirects_created (created), INDEX idx_redirects_source (source),
 CONSTRAINT fk_redirects_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sid VARCHAR(128) NOT NULL UNIQUE,
 token VARCHAR(62) NOT NULL, target TEXT NOT NULL, expires DATETIME NOT NULL, ip VARCHAR(45) NOT NULL,
 used TINYINT(1) NOT NULL DEFAULT 0, INDEX idx_sessions_expires (expires), INDEX idx_sessions_token (token)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS visits (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL, token VARCHAR(62) NOT NULL,
 ip VARCHAR(45) NOT NULL, ua TEXT NOT NULL, device VARCHAR(32) NOT NULL DEFAULT 'Desktop',
 browser VARCHAR(32) NOT NULL DEFAULT 'Other', os VARCHAR(32) NOT NULL DEFAULT 'Other',
 referer TEXT NULL, status VARCHAR(32) NOT NULL, reason TEXT NULL, ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_visits_user_ts (user_id, ts), INDEX idx_visits_token_ts (token, ts),
 INDEX idx_visits_status_ts (status, ts), INDEX idx_visits_ts (ts), INDEX idx_visits_ip (ip),
 CONSTRAINT fk_visits_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS blocked (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ip VARCHAR(45) NOT NULL UNIQUE,
 reason TEXT NULL, ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS apikeys (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL,
 key_value VARCHAR(80) NOT NULL UNIQUE, label VARCHAR(255) NOT NULL DEFAULT '',
 active TINYINT(1) NOT NULL DEFAULT 1, usage_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, last_used DATETIME NULL,
 INDEX idx_apikeys_user (user_id),
 CONSTRAINT fk_apikeys_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS config (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, config_key VARCHAR(64) NOT NULL UNIQUE,
 shortener_url TEXT NULL, shortener_api_key TEXT NULL, enabled TINYINT(1) NOT NULL DEFAULT 0,
 updated DATETIME NULL
) ENGINE=InnoDB;
