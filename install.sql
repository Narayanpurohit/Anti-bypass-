-- Reference schema for Anti Bypass PHP + MySQL.
-- Fresh installations should use the browser setup wizard; it creates these tables automatically.
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'user',
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_login DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS urls (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,
 token VARCHAR(62) NOT NULL UNIQUE,label VARCHAR(190) NOT NULL DEFAULT '',
 target_url TEXT NOT NULL,captcha_enabled TINYINT(1) NOT NULL DEFAULT 1,
 active TINYINT(1) NOT NULL DEFAULT 1,clicks BIGINT UNSIGNED NOT NULL DEFAULT 0,
 visits BIGINT UNSIGNED NOT NULL DEFAULT 0,blocked BIGINT UNSIGNED NOT NULL DEFAULT 0,
 bots BIGINT UNSIGNED NOT NULL DEFAULT 0,captcha_fails BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_visit DATETIME NULL,created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_urls_user_created(user_id,created)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS redirects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,
 token VARCHAR(32) NOT NULL UNIQUE,url TEXT NOT NULL,api_key VARCHAR(100) NULL,
 label VARCHAR(190) NOT NULL DEFAULT '',source VARCHAR(30) NOT NULL DEFAULT 'api',
 permanent TINYINT(1) NOT NULL DEFAULT 1,expires DATETIME NULL,
 created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,clicks BIGINT UNSIGNED NOT NULL DEFAULT 0,
 visits BIGINT UNSIGNED NOT NULL DEFAULT 0,blocked BIGINT UNSIGNED NOT NULL DEFAULT 0,
 bots BIGINT UNSIGNED NOT NULL DEFAULT 0,captcha_fails BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_visit DATETIME NULL,INDEX idx_redirects_user_created(user_id,created),INDEX idx_redirects_expiry(expires)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS visits (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,
 token VARCHAR(62) NOT NULL,ip VARCHAR(45) NOT NULL,ua TEXT,device VARCHAR(30),
 browser VARCHAR(30),os VARCHAR(30),referer TEXT,status VARCHAR(30) NOT NULL,
 reason VARCHAR(255) NOT NULL DEFAULT '',ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_visits_user_ts(user_id,ts),INDEX idx_visits_token_ts(token,ts),INDEX idx_visits_status(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS link_sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,
 sid VARCHAR(100) NOT NULL UNIQUE,token VARCHAR(62) NOT NULL,target TEXT NOT NULL,
 expires DATETIME NOT NULL,ip VARCHAR(45) NOT NULL,used TINYINT(1) NOT NULL DEFAULT 0,
 INDEX idx_link_sessions_expiry(expires)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS blocked_ips (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,
 ip VARCHAR(45) NOT NULL,reason VARCHAR(255) NOT NULL DEFAULT '',
 ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,UNIQUE KEY uq_block_user_ip(user_id,ip)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS api_keys (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,
 api_key VARCHAR(100) NOT NULL UNIQUE,label VARCHAR(190) NOT NULL DEFAULT '',
 active TINYINT(1) NOT NULL DEFAULT 1,usage_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,last_used DATETIME NULL,
 INDEX idx_api_keys_user(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS user_settings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,
 setting_key VARCHAR(100) NOT NULL,value_json LONGTEXT NOT NULL,
 UNIQUE KEY uq_user_setting(user_id,setting_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
